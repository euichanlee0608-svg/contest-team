  PUBLIC_KEY: "",

  /* 첫 화면에 크게 걸리는 질문. 문항 시트의 첫 공통문항이 내려오면 그것으로 대체된다.
     네트워크가 느려도 첫 화면이 비어 보이지 않게 하는 기본값이다. */
